export type BuildAppOptions = {
  deps: AppDeps;
  corsOrigins?: string[];
  logger?: FastifyServerOptions["logger"];
  /** Disable in tests that hammer the auth endpoints. */
  rateLimit?: boolean;
  /** Trust X-Forwarded-For (the API runs behind the web app's proxy), so rate limits see the real client. */
  trustProxy?: boolean;
};

type ErrorBody = { error: { code: string; message: string; issues?: { path: string; message: string }[] } };

export async function buildApp(options: BuildAppOptions) {
  const app = Fastify({
    logger: options.logger ?? false,
    trustProxy: options.trustProxy ?? false,
    // Ids are generated by the database; this only names log lines.
    genReqId: () => crypto.randomUUID(),
  }).withTypeProvider<ZodTypeProvider>();

  app.setValidatorCompiler(validatorCompiler);
  app.setSerializerCompiler(serializerCompiler);
  app.decorate("deps", options.deps);
  app.decorateRequest("auth", null);
  app.decorateRequest("membership", null);

  app.setErrorHandler((error: FastifyError, request, reply) => {
    const send = (status: number, body: ErrorBody) => reply.code(status).send(body);

    if (hasZodFastifySchemaValidationErrors(error)) {
      return send(400, {
        error: {
          code: "validation_error",
          message: "Dati non validi",
          issues: error.validation.map((v) => ({
            path: v.instancePath.replace(/^\//, "").replaceAll("/", "."),
            message: v.message ?? "Valore non valido",
          })),
        },
      });
    }
    if (error instanceof AppError) {
      return send(error.statusCode, {
        error: {
          code: error.code,
          message: error.message,
          ...(error.issues ? { issues: error.issues } : {}),
        },
      });
    }
    switch (pgErrorCode(error)) {
      case PG_UNIQUE_VIOLATION:
        return send(409, {
          error: { code: "already_exists", message: "Esiste già un elemento con questo nome" },
        });
      case PG_FOREIGN_KEY_VIOLATION:
        return send(400, {
          error: { code: "invalid_reference", message: "Riferimento a un elemento inesistente" },
        });
      case PG_EXCLUSION_VIOLATION:
        return send(409, {
          error: {
            code: "table_taken",
            message: "Il tavolo è già occupato in quell'orario da un'altra prenotazione",
          },
        });
      case PG_CHECK_VIOLATION:
        return send(400, { error: { code: "validation_error", message: "Dati non validi" } });
    }
    if (error.statusCode && error.statusCode < 500) {
      return send(error.statusCode, { error: { code: error.code ?? "bad_request", message: error.message } });
    }
    request.log.error({ err: error }, "Unhandled error");
    return send(500, { error: { code: "internal_error", message: "Errore interno, riprova tra poco" } });
  });

  app.setNotFoundHandler((_request, reply) =>
    reply
      .code(404)
      .send({ error: { code: "not_found", message: "Endpoint non trovato" } } satisfies ErrorBody),
  );

  await app.register(helmet);
  await app.register(cors, { origin: options.corsOrigins ?? [], credentials: true });
  // Routes opt in with `config.rateLimit`; without the plugin that config is simply ignored.
  if (options.rateLimit !== false) await app.register(rateLimit, { global: false });
  await app.register(swagger, {
    openapi: { info: { title: "TwentyReserve API", version: "0.1.0" } },
    transform: jsonSchemaTransform,
  });

  app.get("/health", async () => ({ status: "ok" }));
  app.get("/docs/openapi.json", async () => app.swagger());

  await app.register(
    async (v1) => {
      await v1.register(authRoutes);
      await v1.register(publicRoutes, { prefix: "/public" });
      await v1.register(internalRoutes, { prefix: "/internal" });
      await v1.register(adminRoutes, { prefix: "/admin" });

      // For uptime checks (.github/workflows/monitor.yml): answers 503 when the database is down.
      v1.get("/health", async (_request, reply) => {
        const started = Date.now();
        try {
          await app.deps.db.execute(sql`select 1`);
          return { data: { status: "ok", database: "ok", latencyMs: Date.now() - started } };
        } catch (error) {
          app.log.error({ err: error }, "Health check: database unreachable");
          return reply
            .code(503)
            .send({ error: { code: "unhealthy", message: "Database non raggiungibile" } });
        }
      });

      v1.get("/templates", async (request) => {
        await authenticate(request);
        return { data: listTemplates() };
      });

      await v1.register(
        async (scope) => {
          restaurantScope(scope);
          await scope.register(restaurantRoutes);
          await scope.register(roomRoutes);
          await scope.register(tableRoutes);
          await scope.register(combinationRoutes);
          await scope.register(serviceRoutes);
          await scope.register(durationRuleRoutes);
          await scope.register(calendarExceptionRoutes);
          await scope.register(tableBlockRoutes);
          await scope.register(setupRoutes);
          await scope.register(reservationRoutes);
          await scope.register(waitlistRoutes);
          await scope.register(reviewRoutes);
          await scope.register(guestRoutes);
          await scope.register(bookingPageRoutes);
          await scope.register(teamRoutes);
          await scope.register(importRoutes);
        },
        { prefix: "/restaurants/:restaurantId" },
      );
    },
    { prefix: "/v1" },
  );

  return app;
}

export type App = Awaited<ReturnType<typeof buildApp>>;
